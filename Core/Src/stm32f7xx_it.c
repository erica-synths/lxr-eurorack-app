/**
  * @brief This function handles Hard fault interrupt.
  */
void HardFault_Handler(void)
{
  /* USER CODE BEGIN HardFault_IRQn 0 */

  /* USER CODE END HardFault_IRQn 0 */
  while (1)
  {
    /* USER CODE BEGIN W1_HardFault_IRQn 0 */
#ifdef DEBUG
	  /* Configurable Fault Status Register, split up for the debugger */
	  volatile uint32_t error = *(uint32_t *) 0xE000ED28;
	  volatile uint16_t UFSR = error>>16;
	  volatile uint8_t BFSR = (error&0x0000ff00)>>8;
	  volatile uint8_t MMFSR = error &0xff;
	  (void)UFSR; (void)BFSR; (void)MMFSR;
#endif
    /* USER CODE END W1_HardFault_IRQn 0 */
  }
}

